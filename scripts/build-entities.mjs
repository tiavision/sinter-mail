// Writes sinter/parser/entities.ts, the HTML parser's table of named character references, from
// character-entities (every name, as written with `;`) and character-entities-legacy (the names the
// standard also recognizes without `;`).
//
//   npm run build:entities             write sinter/parser/entities.ts
//   npm run build:entities -- --check  fail if sinter/parser/entities.ts is not what this script writes
//
// The table is packed as sinter-markdown's is (its scripts/build-parser.mjs): the entries sorted by code
// point, each its first code point's distance from the one before in base 36 and `+` and its second code
// point in base 36 if it has one, then its names (those that stand for the same characters, joined by `,`,
// each with `!` if it also works without `;`), all separated by spaces. Unpacking all of it takes a few
// milliseconds, so the parser does it on the first reference it needs it for. Before that it has a small
// table: the legacy names and those emails use most (`*` in the table), each with its one character from
// CHARS, which most emails never get past. Decoding never goes through the DOM.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { characterEntities } from 'character-entities';
import { characterEntitiesLegacy } from 'character-entities-legacy';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const OUT = here('../sinter/parser/entities.ts');
const pkg = (name) => JSON.parse(readFileSync(here(`../node_modules/${name}/package.json`), 'utf8')).version;
const VERSIONS = ['character-entities', 'character-entities-legacy'].map((n) => `${n} ${pkg(n)}`).join(' and ');

const legacy = new Set(characterEntitiesLegacy);
for (const name of legacy) if (!(name in characterEntities)) throw new Error(`character-entities-legacy: ${name} is not in character-entities`);

// the names emails write most, beyond the legacy ones: punctuation, arrows, currency, spaces and the marks
// preheaders are padded with
const COMMON = 'apos mdash ndash hellip lsquo rsquo ldquo rdquo bdquo bull euro trade rarr larr minus zwnj zwj lrm rlm thinsp ensp emsp check hearts star'.split(' ');
const common = new Set([...legacy, ...COMMON]);
for (const name of common) if (characterEntities[name]?.length !== 1) throw new Error(`character-entities: ${name} is not one character`);
const escape = (c) => (c === "'" || c === '\\' ? '\\' + c : c >= ' ' && c <= '~' ? c : c <= '\xFF' ? `\\x${c.charCodeAt(0).toString(16).toUpperCase().padStart(2, '0')}` : `\\u${c.charCodeAt(0).toString(16).toUpperCase().padStart(4, '0')}`);

const entries = Object.entries(characterEntities)
  .map(([name, value]) => [name, [...value].map((c) => c.codePointAt(0))])
  .sort(([an, a], [bn, b]) => a[0] - b[0] || (a[1] ?? -1) - (b[1] ?? -1) || (an < bn ? -1 : 1));
const fields = [];
let last = 0, key = '', chars = '';
for (const [name, [first, second, more]] of entries) {
  if (more !== undefined || !/^[a-z\d]+$/i.test(name)) throw new Error(`character-entities: cannot pack ${name}`);
  const marked = legacy.has(name) ? name + '!' : common.has(name) ? name + '*' : name;
  if (common.has(name)) chars += escape(characterEntities[name]);
  if (`${first} ${second}` === key) { fields[fields.length - 1] += ',' + marked; continue; }
  key = `${first} ${second}`;
  fields.push(`${(first - last).toString(36)}${second === undefined ? '' : '+' + second.toString(36)}`, marked);
  last = first;
}
const PACKED = fields.join(' ');

const code = `// Generated by scripts/build-entities.mjs from ${VERSIONS}; do not edit.
// The named character references, packed (see the script): the legacy ones and those emails use most are
// ready when the parser loads, the rest unpacked on the first reference that needs them.

const PACKED =
  '${PACKED}';
// the characters of the names marked \`!\` or \`*\`, in their order
const CHARS =
  '${chars}';

/** the names that are also references without \`;\` (\`&amp\`, \`&copy\`) */
export const LEGACY: ReadonlySet<string> = new Set();
const COMMON = new Map<string, string>();
const MARKED = /[ ,]([A-Za-z\\d]+)([!*])/g;
for (let m, i = 0; (m = MARKED.exec(PACKED)); i++) {
  COMMON.set(m[1], CHARS[i]);
  if (m[2] === '!') (LEGACY as Set<string>).add(m[1]);
}

// filled once, by the first reference COMMON does not have; the same table for every parse after it
const ALL = new Map<string, string>();

/** every named character reference, by its name without \`;\` */
export function entities(): ReadonlyMap<string, string> {
  if (ALL.size) return ALL;
  const fields = PACKED.split(' ');
  for (let i = 0, code = 0; i < fields.length; i += 2) {
    // parseInt reads the distance up to the \`+\`
    const f = fields[i], plus = f.indexOf('+');
    code += parseInt(f, 36);
    const value = String.fromCodePoint(code) + (plus < 0 ? '' : String.fromCodePoint(parseInt(f.slice(plus + 1), 36)));
    for (const name of fields[i + 1].split(',')) {
      const mark = name.charCodeAt(name.length - 1);
      ALL.set(mark === 33 || mark === 42 ? name.slice(0, -1) : name, value);
    }
  }
  return ALL;
}

/** the characters of the named reference \`name\` (without \`;\`), or undefined */
export const entity = (name: string): string | undefined => COMMON.get(name) ?? entities().get(name);
`;

if (process.argv.includes('--check')) {
  let now = '';
  try { now = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
  if (now !== code) { console.error('sinter/parser/entities.ts is out of date: run `npm run build:entities`'); process.exit(1); }
  console.log('sinter/parser/entities.ts is up to date');
} else {
  writeFileSync(OUT, code);
  console.log(`wrote sinter/parser/entities.ts (${(code.length / 1024).toFixed(1)} kB)`);
}
