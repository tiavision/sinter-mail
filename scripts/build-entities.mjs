// Writes sinter/parser/entities.ts, the HTML parser's table of named character references, from
// character-entities (every name, as written with `;`) and character-entities-legacy (the names the
// standard also recognizes without `;`).
//
//   npm run build:entities             write sinter/parser/entities.ts
//   npm run build:entities -- --check  fail if sinter/parser/entities.ts is not what this script writes
//
// The table is packed as sinter-markdown's is (its scripts/build-parser.mjs): the entries sorted by code
// point, each its first code point's distance from the one before in base 36 and `+` and its second code
// point in base 36 if it has one, then its names (those that stand for the same characters, joined by `,`,
// each with `!` if it also works without `;`), all separated by spaces. The parser unpacks it once, when it
// loads; decoding never goes through the DOM.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { characterEntities } from 'character-entities';
import { characterEntitiesLegacy } from 'character-entities-legacy';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const OUT = here('../sinter/parser/entities.ts');
const pkg = (name) => JSON.parse(readFileSync(here(`../node_modules/${name}/package.json`), 'utf8')).version;
const VERSIONS = ['character-entities', 'character-entities-legacy'].map((n) => `${n} ${pkg(n)}`).join(' and ');

const legacy = new Set(characterEntitiesLegacy);
for (const name of legacy) if (!(name in characterEntities)) throw new Error(`character-entities-legacy: ${name} is not in character-entities`);

const entries = Object.entries(characterEntities)
  .map(([name, value]) => [name, [...value].map((c) => c.codePointAt(0))])
  .sort(([an, a], [bn, b]) => a[0] - b[0] || (a[1] ?? -1) - (b[1] ?? -1) || (an < bn ? -1 : 1));
const fields = [];
let last = 0, key = '';
for (const [name, [first, second, more]] of entries) {
  if (more !== undefined || !/^[a-z\d]+$/i.test(name)) throw new Error(`character-entities: cannot pack ${name}`);
  const marked = legacy.has(name) ? name + '!' : name;
  if (`${first} ${second}` === key) { fields[fields.length - 1] += ',' + marked; continue; }
  key = `${first} ${second}`;
  fields.push(`${(first - last).toString(36)}${second === undefined ? '' : '+' + second.toString(36)}`, marked);
  last = first;
}
const PACKED = fields.join(' ');

const code = `// Generated by scripts/build-entities.mjs from ${VERSIONS}; do not edit.
// The named character references, packed (see the script): unpacked once, when the parser loads.

const PACKED =
  '${PACKED}';

/** every named character reference, by its name without \`;\` */
export const ENTITIES: ReadonlyMap<string, string> = new Map();
/** the names that are also references without \`;\` (\`&amp\`, \`&copy\`) */
export const LEGACY: ReadonlySet<string> = new Set();

const fields = PACKED.split(' ');
for (let i = 0, code = 0; i < fields.length; i += 2) {
  const [delta, second] = fields[i].split('+');
  code += parseInt(delta, 36);
  const value = String.fromCodePoint(code) + (second ? String.fromCodePoint(parseInt(second, 36)) : '');
  for (const name of fields[i + 1].split(',')) {
    const bare = name.replace('!', '');
    (ENTITIES as Map<string, string>).set(bare, value);
    if (bare !== name) (LEGACY as Set<string>).add(bare);
  }
}
`;

if (process.argv.includes('--check')) {
  let now = '';
  try { now = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
  if (now !== code) { console.error('sinter/parser/entities.ts is out of date: run `npm run build:entities`'); process.exit(1); }
  console.log('sinter/parser/entities.ts is up to date');
} else {
  writeFileSync(OUT, code);
  console.log(`wrote sinter/parser/entities.ts (${(code.length / 1024).toFixed(1)} kB)`);
}
